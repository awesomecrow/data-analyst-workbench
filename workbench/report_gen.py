def generate_interactive_dashboard(project_dir: str = ".") -> str:
    """Generate self-contained, 100% offline interactive BI dashboard HTML from DuckDB marts."""
    duckdb_path = os.path.join(project_dir, "data", "analytics.duckdb")
    marts_dir = os.path.join(project_dir, "data", "marts")
    processed_dir = os.path.join(project_dir, "data", "processed")
    reports_dir = os.path.join(project_dir, "reports")
    os.makedirs(reports_dir, exist_ok=True)
    out_path = os.path.join(reports_dir, "index.html")

    project_name = os.path.basename(os.path.abspath(project_dir)).replace("_", " ").title()

    conn = duckdb.connect(duckdb_path if os.path.exists(duckdb_path) else ":memory:")

    # Find available marts
    parquet_files = glob.glob(os.path.join(marts_dir, "*.parquet")) + glob.glob(os.path.join(processed_dir, "*.parquet"))
    for pf in parquet_files:
        tbl = os.path.splitext(os.path.basename(pf))[0]
        try:
            conn.execute(f"CREATE OR REPLACE VIEW {tbl} AS SELECT * FROM '{pf}'")
        except Exception:
            pass

    # Inspect tables in DuckDB
    tables = [r[0] for r in conn.execute("SHOW TABLES").fetchall()]

    kpi_cards = []
    chart_1_title = "Primary Dimension Breakdown"
    chart_1_json = json.dumps({"categories": [], "values": []})
    chart_2_title = "Segment Distribution"
    chart_2_json = json.dumps({"data": []})
    table_title = "Detailed Performance Mart"
    table_html = "<p style='color:#a1a1aa;padding:16px;'>No analytical marts found. Run 'analyst run' to materialize marts.</p>"

    if tables:
        # Check for SwiftRoute / Logistics tables or Store / Restaurant tables
        mart_candidates = [t for t in tables if t.startswith("mart_") or t.startswith("fact_")]
        primary_tbl = mart_candidates[0] if mart_candidates else tables[0]
        for candidate in ["mart_hub_performance", "mart_monthly_sla", "mart_store_performance", "fact_shipments", "fact_order_details"]:
            if candidate in tables:
                primary_tbl = candidate
                break

        # Generate KPIs
        total_rows = conn.execute(f"SELECT COUNT(*) FROM {primary_tbl}").fetchone()[0]
        kpi_cards.append(f"""
        <div class="kpi-card">
          <div class="kpi-title">Analytical Mart</div>
          <div class="kpi-value">{primary_tbl}</div>
          <div class="kpi-sub">{total_rows:,} total records</div>
        </div>
        """)

        # Hub / Store specific heuristics
        if "mart_hub_performance" in tables:
            df_kpi = conn.execute("SELECT SUM(total_shipments), AVG(on_time_rate_pct), AVG(avg_lead_time_hours), SUM(complaint_count) FROM mart_hub_performance").fetchone()
            tot_ship, avg_sla, avg_lead, tot_comp = df_kpi
            kpi_cards = [
                f"""<div class="kpi-card"><div class="kpi-title">Total Shipments</div><div class="kpi-value">{int(tot_ship or 0):,}</div><div class="kpi-sub">H1 2026 Cohort</div></div>""",
                f"""<div class="kpi-card"><div class="kpi-title">On-Time SLA Rate</div><div class="kpi-value" style="color: #ef4444;">{float(avg_sla or 0):.1f}%</div><div class="kpi-sub" style="color:#ef4444;">Target &ge; 92.0%</div></div>""",
                f"""<div class="kpi-card"><div class="kpi-title">Avg Lead Time</div><div class="kpi-value" style="color: #f59e0b;">{float(avg_lead or 0):.1f} hrs</div><div class="kpi-sub">Service SLA Target</div></div>""",
                f"""<div class="kpi-card"><div class="kpi-title">Customer Complaints</div><div class="kpi-value">{int(tot_comp or 0):,}</div><div class="kpi-sub" style="color:#ef4444;">Rate &ge; 12.1%</div></div>""",
            ]
            chart_1_title = "On-Time Delivery Rate by Destination Hub (%)"
            hub_rows = conn.execute("SELECT destination_hub_name, on_time_rate_pct FROM mart_hub_performance ORDER BY on_time_rate_pct DESC").fetchall()
            chart_1_json = json.dumps({
                "categories": [r[0] for r in hub_rows],
                "values": [round(r[1], 1) for r in hub_rows]
            })

            chart_2_title = "Shipment Volume Share by Hub"
            vol_rows = conn.execute("SELECT destination_hub_name, total_shipments FROM mart_hub_performance ORDER BY total_shipments DESC").fetchall()
            chart_2_json = json.dumps({
                "data": [{"name": r[0], "value": r[1]} for r in vol_rows]
            })

            table_title = "Destination Hub Reliability & Exception Scorecard"
            t_df = conn.execute("SELECT destination_hub_name AS Hub, total_shipments AS Shipments, on_time_shipments AS OnTime, on_time_rate_pct AS OnTimeRate_Pct, gap_vs_target_pct AS SLAGap, avg_lead_time_hours AS AvgLeadTime_Hrs, complaint_count AS Complaints FROM mart_hub_performance").fetch_df()
            table_html = t_df.to_html(classes="table", index=False, border=0)

        elif "mart_store_performance" in tables:
            df_kpi = conn.execute("SELECT SUM(actual_revenue), SUM(actual_profit), AVG(attainment_pct), SUM(actual_orders) FROM mart_store_performance").fetchone()
            rev, prof, att, ords = df_kpi
            kpi_cards = [
                f"""<div class="kpi-card"><div class="kpi-title">Total Net Revenue</div><div class="kpi-value">${float(rev or 0):,.2f}</div><div class="kpi-sub">100% Reconciled</div></div>""",
                f"""<div class="kpi-card"><div class="kpi-title">Gross Profit</div><div class="kpi-value">${float(prof or 0):,.2f}</div><div class="kpi-sub">Gross Margin: {round((prof/rev*100) if rev else 0, 1)}%</div></div>""",
                f"""<div class="kpi-card"><div class="kpi-title">Target Attainment</div><div class="kpi-value">{float(att or 0):.1f}%</div><div class="kpi-sub">Across All Stores</div></div>""",
                f"""<div class="kpi-card"><div class="kpi-title">Verified Transactions</div><div class="kpi-value">{int(ords or 0):,}</div><div class="kpi-sub">Zero Corruptions</div></div>""",
            ]
            chart_1_title = "Store Branch Net Revenue ($)"
            store_rows = conn.execute("SELECT store_name, actual_revenue FROM mart_store_performance ORDER BY actual_revenue DESC").fetchall()
            chart_1_json = json.dumps({
                "categories": [r[0] for r in store_rows],
                "values": [round(r[1], 2) for r in store_rows]
            })

            chart_2_title = "Revenue Contribution Share"
            chart_2_json = json.dumps({
                "data": [{"name": r[0], "value": round(r[1], 2)} for r in store_rows]
            })

            table_title = "Store Attainment & Profitability Mart"
            t_df = conn.execute("SELECT * FROM mart_store_performance").fetch_df()
            table_html = t_df.to_html(classes="table", index=False, border=0)

        else:
            # Generic table auto-profiling for ANY table / mart
            desc_rows = conn.execute(f"DESCRIBE {primary_tbl}").fetchall()
            cols = [col[0] for col in desc_rows]
            dtypes = {col[0]: col[1].upper() for col in desc_rows}

            # Find candidate categorical column with reasonable cardinality (2..60)
            cat_col = None
            for c in cols:
                dt = dtypes.get(c, "")
                if "VARCHAR" in dt or "TEXT" in dt or "STRING" in dt:
                    try:
                        cardinality = conn.execute(f"SELECT COUNT(DISTINCT {c}) FROM {primary_tbl}").fetchone()[0]
                        if 1 < cardinality <= 60:
                            cat_col = c
                            break
                    except Exception:
                        pass

            if not cat_col and cols:
                for c in cols:
                    try:
                        cardinality = conn.execute(f"SELECT COUNT(DISTINCT {c}) FROM {primary_tbl}").fetchone()[0]
                        if 1 < cardinality <= 60:
                            cat_col = c
                            break
                    except Exception:
                        pass

            if cat_col:
                chart_1_title = f"Top 10 Breakdown by {cat_col.replace('_', ' ').title()}"
                chart_2_title = f"{cat_col.replace('_', ' ').title()} Share Distribution"

                cat_rows = conn.execute(
                    f"SELECT COALESCE(CAST({cat_col} AS VARCHAR), 'Unknown') AS label, COUNT(*) AS count_val FROM {primary_tbl} GROUP BY 1 ORDER BY 2 DESC LIMIT 10"
                ).fetchall()

                chart_1_json = json.dumps({
                    "categories": [str(r[0]) for r in cat_rows],
                    "values": [int(r[1]) for r in cat_rows]
                })
                chart_2_json = json.dumps({
                    "data": [{"name": str(r[0]), "value": int(r[1])} for r in cat_rows]
                })

                top_cat = cat_rows[0][0] if cat_rows else "N/A"
                top_count = cat_rows[0][1] if cat_rows else 0
                kpi_cards.append(f"""
                <div class="kpi-card">
                  <div class="kpi-title">Top {cat_col.replace('_', ' ').title()}</div>
                  <div class="kpi-value">{top_cat}</div>
                  <div class="kpi-sub">{top_count:,} occurrences ({round(top_count/total_rows*100, 1) if total_rows else 0}%)</div>
                </div>
                """)

            kpi_cards.append(f"""
            <div class="kpi-card">
              <div class="kpi-title">Dimensional Columns</div>
              <div class="kpi-value">{len(cols)}</div>
              <div class="kpi-sub">{", ".join(cols[:3])}...</div>
            </div>
            """)

            table_title = f"{primary_tbl.replace('_', ' ').title()} - Detailed Records"
            t_df = conn.execute(f"SELECT * FROM {primary_tbl} LIMIT 25").fetch_df()
            table_html = t_df.to_html(classes="table", index=False, border=0)

    html_content = HTML_TEMPLATE.format(
        project_name=project_name,
        kpi_cards_html="".join(kpi_cards),
        chart_1_title=chart_1_title,
        chart_1_json=chart_1_json,
        chart_2_title=chart_2_title,
        chart_2_json=chart_2_json,
        table_title=table_title,
        table_html=table_html
    )

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(html_content)

    conn.close()
    return out_path
